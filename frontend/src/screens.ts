export type Screen = (typeof screens)[number];

export const navigationGroups = Array.from(
  screens.reduce((topMap, item) => {
    if (!topMap.has(item.topMenu))
      topMap.set(item.topMenu, new Map<string, ScreenConfig[]>());
    const middleMap = topMap.get(item.topMenu)!;
    if (!middleMap.has(item.middleMenu)) middleMap.set(item.middleMenu, []);
    middleMap.get(item.middleMenu)!.push(item);
    return topMap;
  }, new Map<string, Map<string, ScreenConfig[]>>()),
).map(([topMenu, middleMap]) => ({
  topMenu,
  middleMenus: Array.from(middleMap).map(([middleMenu, items]) => ({
    middleMenu,
    items,
  })),
}));
