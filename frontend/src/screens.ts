export type FieldType = "text" | "textarea" | "select" | "date" | "number";

export type ScreenField = {
  key: string;
  label: string;
  type?: FieldType;
  readonly?: boolean;
  options?: string[];
  placeholder?: string;
  helper?: string;
};

export type ScreenAction = {
  label: string;
  kind:
    | "create"
    | "edit"
    | "save"
    | "readonly"
    | "logicalDelete"
    | "terminate"
    | "local"
    | "navigate";
  description: string;
};

export type ScreenConfig = {
  id: string;
  route: string;
  title: string;
  apiPath: string;
  menuPath: string;
  topMenu: string;
  middleMenu: string;
  entity: string;
  archetype: string;
  goal: string;
  primaryCta: string;
  readonlyNotice?: string;
  oqNotice?: string;
  columns: ScreenField[];
  editableFields: ScreenField[];
  readonlyFields?: ScreenField[];
  searchFields: ScreenField[];
  actions: ScreenAction[];
  supportsCreate?: boolean;
  noMutation?: boolean;
  secondaryApis?: { label: string; path: string }[];
};

const ynOptions = ["Y", "N"];
const statusOptions = [
  "ACTIVE",
  "INACTIVE",
  "PENDING",
  "RUNNING",
  "COMPLETED",
  "FAILED",
  "TERMINATED",
  "REVOKED",
  "EXPIRED",
  "STOPPED",
];
const baseColumns: ScreenField[] = [
  { key: "id", label: "식별자", readonly: true },
  { key: "title", label: "명칭" },
  { key: "status", label: "상태", type: "select", options: statusOptions },
  { key: "useYn", label: "사용여부", type: "select", options: ynOptions },
  { key: "updatedAt", label: "수정일시", readonly: true },
];
const baseSearch: ScreenField[] = [
  {
    key: "keyword",
    label: "통합 검색어",
    placeholder: "식별자, 명칭, payload 필드 검색",
  },
];
const baseEdit: ScreenField[] = [
  {
    key: "id",
    label: "식별자",
    helper: "기존 레코드에서는 변경할 수 없습니다.",
  },
  { key: "title", label: "명칭" },
  { key: "status", label: "상태", type: "select", options: statusOptions },
  { key: "useYn", label: "사용여부", type: "select", options: ynOptions },
];

function screen(
  config: Omit<
    ScreenConfig,
    "columns" | "editableFields" | "searchFields" | "actions"
  > & {
    columns?: ScreenField[];
    editableFields?: ScreenField[];
    readonlyFields?: ScreenField[];
    searchFields?: ScreenField[];
    actions?: ScreenAction[];
  },
): ScreenConfig {
  return {
    columns: config.columns ?? baseColumns,
    editableFields: config.editableFields ?? baseEdit,
    readonlyFields: config.readonlyFields,
    searchFields: config.searchFields ?? baseSearch,
    actions: config.actions ?? [
      {
        label: "검색",
        kind: "local",
        description: `${config.apiPath} GET 목록 조회`,
      },
      {
        label: "신규 등록",
        kind: "create",
        description: `${config.apiPath} POST 신규 저장`,
      },
      {
        label: "수정",
        kind: "edit",
        description: `${config.apiPath} POST 변경 저장`,
      },
    ],
    ...config,
  };
}

